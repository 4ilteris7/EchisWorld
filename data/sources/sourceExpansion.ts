import type {
  SourceDefinition,
  SourceProfile,
  SourceRegionScope,
  SourceTargetScreen,
} from "./sourceTypes";

type RssSourceInput = {
  id: string;
  name: string;
  category: string;
  feedUrl: string;
  regionScope: SourceRegionScope;
  targetScreens: SourceTargetScreen[];
  sourceProfile?: SourceProfile;
};

function baseUrlFromFeed(feedUrl: string): string {
  const url = new URL(feedUrl);
  return `${url.protocol}//${url.hostname}/`;
}

function rssSource(input: RssSourceInput): SourceDefinition {
  return {
    id: input.id,
    name: input.name,
    category: input.category,
    accessType: "rss",
    candidateStatus: "candidate_test",
    sourceStatus: "established_media",
    verificationStatus: "source_reported",
    sourceBasis: "single_public_source",
    extractionMethod: "rss_summary",
    baseUrl: baseUrlFromFeed(input.feedUrl),
    candidateFeedUrl: input.feedUrl,
    language: "en",
    regionScope: input.regionScope,
    targetScreens: input.targetScreens,
    sourceProfile: input.sourceProfile ?? "general_news",
    markerLocationStrategy: "item_location",
    notes: "Public RSS source added for broader EchisWorld coverage.",
  };
}

